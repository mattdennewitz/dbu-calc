function familyForOpenRouterModel(entry) {
  const identity = `${entry.id} ${entry.name}`.toLowerCase();
  return (
    OPENROUTER_FAMILIES.find((family) =>
      new RegExp(`(^|[^a-z0-9])${family}($|[^a-z0-9])`).test(identity),
    ) ?? null
  );
}

function pricePerMillion(value) {
  if (typeof value !== "string" && typeof value !== "number") return null;
  if (typeof value === "string" && value.trim() === "") return null;
  const pricePerToken = Number(value);
  return Number.isFinite(pricePerToken) && pricePerToken >= 0
    ? pricePerToken * 1_000_000
    : null;
}

function normalizeOpenRouterModels(entries) {
  return entries.flatMap((entry) => {
    if (
      !entry ||
      typeof entry.id !== "string" ||
      typeof entry.name !== "string"
    )
      return [];
    const family = familyForOpenRouterModel(entry);
    if (
      !family ||
      !entry.architecture?.input_modalities?.includes("text") ||
      entry.architecture?.output_modalities?.length !== 1 ||
      entry.architecture.output_modalities[0] !== "text"
    )
      return [];
    const pricing = entry.pricing ?? {};
    return [
      {
        id: entry.id,
        name: entry.name,
        family,
        input: pricePerMillion(pricing.prompt),
        output: pricePerMillion(pricing.completion),
        cacheRead: pricePerMillion(pricing.input_cache_read),
        cacheWrite: pricePerMillion(pricing.input_cache_write),
      },
    ];
  });
}

