import * as Plot from "@observablehq/plot";
import { parseUsage, summarizeUsage } from "./usage.js";

export function mountUsageExplorer(root, onApply) {
  root.innerHTML = `<div class="section-head"><h2>IMPORT <span>Explore actual OpenRouter usage</span></h2><button class="text-button" id="usage-clear" hidden>Clear import</button></div>
    <label>Usage export (CSV or JSON)<input id="usage-file" type="file" accept=".csv,.json,text/csv,application/json"></label>
    <p class="hint">Generated by <code>npm run openrouter:usage</code>. Parsed locally; nothing is uploaded. Imported periods are compared as-is, not extrapolated to a month.</p>
    <p id="usage-status" class="hint" role="status"></p>
    <div id="usage-explorer" hidden><div class="usage-filters"></div><div class="usage-date-filters"><label>From (UTC)<input id="usage-from" type="date"></label><label>To (UTC)<input id="usage-to" type="date"></label></div><div id="usage-summary" class="usage-summary"></div><div class="usage-charts"><div><h3>Spend over time</h3><div id="usage-daily"></div></div><div><h3>Spend by model</h3><div id="usage-models"></div></div></div>
    <p id="usage-warnings" class="hint"></p><button id="usage-apply" class="primary-button">Apply selected workload & actual spend</button></div>`;
  const el = (id) => root.querySelector(`#${id}`);
  let rows = [],
    selected = [];
  const filters = [
    ["workspace_id", "Workspace"],
    ["api_key_hash", "API key"],
    ["creator_user_id", "Key creator"],
    ["model", "Model"],
  ];
  const filterElements = new Map();
  const redraw = () => {
    selected = rows.filter(
      (row) =>
        (!el("usage-from").value || row.date >= el("usage-from").value) &&
        (!el("usage-to").value || row.date <= el("usage-to").value) &&
        filters.every(
          ([key]) =>
            !filterElements.get(key).value ||
            String(row[key] ?? "") === filterElements.get(key).value,
        ),
    );
    const summary = summarizeUsage(selected);
    const format = (n) =>
      n == null
        ? "unavailable"
        : new Intl.NumberFormat("en-US", {
            style: "currency",
            currency: "USD",
          }).format(n);
    el("usage-summary").textContent =
      `${selected.length} rows · ${summary.models.length} models · ${summary.dates[0] ?? "—"} to ${summary.dates.at(-1) ?? "—"} · OpenRouter credits: ${format(summary.spend)} · external BYOK inference: ${format(summary.byok)}`;
    el("usage-warnings").textContent = [summary.error, ...summary.warnings]
      .filter(Boolean)
      .join(" ");
    el("usage-apply").disabled = !!summary.error;
    const daily = new Map(),
      models = new Map();
    for (const row of selected)
      if (row.spend_usd != null) {
        daily.set(row.date, (daily.get(row.date) ?? 0) + row.spend_usd);
        models.set(row.model, (models.get(row.model) ?? 0) + row.spend_usd);
      }
    const dates = [...daily]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([date, spend]) => ({ date: new Date(`${date}T00:00:00Z`), spend }));
    const modelRows = [...models]
      .map(([model, spend]) => ({ model, spend }))
      .sort((a, b) => b.spend - a.spend);
    const width = Math.max(
      260,
      Math.floor(root.clientWidth / (root.clientWidth > 760 ? 2 : 1)) - 40,
    );
    el("usage-daily").replaceChildren(
      Plot.plot({
        width,
        height: 260,
        marginLeft: 65,
        x: { type: "utc", label: "UTC date" },
        y: { label: "OpenRouter spend (USD)", grid: true },
        marks: [
          Plot.ruleY([0]),
          Plot.lineY(dates, {
            x: "date",
            y: "spend",
            stroke: "#245d46",
            tip: true,
          }),
          Plot.dot(dates, {
            x: "date",
            y: "spend",
            fill: "#245d46",
            tip: true,
          }),
        ],
      }),
    );
    el("usage-models").replaceChildren(
      Plot.plot({
        width,
        height: Math.max(260, modelRows.length * 28 + 60),
        marginLeft: Math.min(210, width * 0.48),
        x: { label: "OpenRouter spend (USD)", grid: true },
        y: { label: null, domain: modelRows.map((d) => d.model) },
        marks: [
          Plot.barX(modelRows, {
            x: "spend",
            y: "model",
            fill: "#668c52",
            tip: true,
          }),
          Plot.ruleX([0]),
        ],
      }),
    );
  };
  el("usage-file").addEventListener("change", async (e) => {
    const file = e.target.files[0];
    if (!file) return;
    try {
      if (file.size > 25 * 1024 * 1024)
        throw new Error(
          "File exceeds the 25 MB import limit. Export a shorter period or one workspace.",
        );
      const next = parseUsage(await file.text());
      rows = next;
      const container = root.querySelector(".usage-filters");
      container.replaceChildren();
      filterElements.clear();
      for (const [key, label] of filters) {
        const wrapper = document.createElement("label");
        wrapper.textContent = label;
        const select = document.createElement("select");
        select.id = `usage-filter-${key}`;
        select.add(new Option("All", ""));
        const representatives = new Map();
        for (const row of rows) {
          const value = String(row[key] ?? "");
          if (value && !representatives.has(value))
            representatives.set(value, row);
        }
        for (const [value, row] of [...representatives].sort(([a], [b]) =>
          a.localeCompare(b),
        )) {
          const name =
            key === "workspace_id"
              ? row.workspace_name
              : key === "api_key_hash"
                ? `${row.key_name || "Unnamed"} · ${value.slice(0, 10)}`
                : key === "creator_user_id"
                  ? row.creator_user_name
                  : value;
          select.add(new Option(name || value, value));
        }
        select.addEventListener("change", redraw);
        wrapper.append(select);
        container.append(wrapper);
        filterElements.set(key, select);
      }
      const dates = rows.map((row) => row.date).sort();
      el("usage-from").value = dates[0];
      el("usage-to").value = dates.at(-1);
      el("usage-explorer").hidden = false;
      el("usage-clear").hidden = false;
      el("usage-status").textContent =
        `Loaded ${file.name}: ${rows.length} rows. Filters update charts and the workload selection.`;
      redraw();
    } catch (error) {
      el("usage-status").textContent =
        `Import failed: ${error.message}. Previous selection retained.`;
    }
  });
  el("usage-apply").addEventListener("click", () => {
    const summary = summarizeUsage(selected);
    if (!summary.error) onApply(summary);
  });
  el("usage-clear").addEventListener("click", () => {
    rows = [];
    selected = [];
    el("usage-file").value = "";
    el("usage-explorer").hidden = true;
    el("usage-clear").hidden = true;
    el("usage-status").textContent =
      "Import cleared. Previously applied workload is unchanged.";
  });
  for (const id of ["usage-from", "usage-to"])
    el(id).addEventListener("change", redraw);
  let previousWidth = 0;
  const observer = new ResizeObserver(() => {
    const width = root.clientWidth;
    if (rows.length && width !== previousWidth) {
      previousWidth = width;
      redraw();
    }
  });
  observer.observe(root);
}
